"""Custom LLM-as-judge response quality evaluator for ADK evaluation."""

import os
from typing import Any, Dict


def evaluate(instance: Dict[str, Any]) -> Dict[str, Any]:
    """Evaluate agent response quality, pedagogical guidance, and tool compliance."""
    agent_data = instance.get("agent_data") or {}
    turns = agent_data.get("turns", [])
    response_text = ""
    for turn in turns:
        for content in turn.get("contents", []):
            for part in content.get("parts", []):
                if "text" in part:
                    response_text += part["text"] + " "

    # Check for meaningful response and guardrails
    if not response_text.strip():
        return {
            "score": 0.0,
            "explanation": "No text response generated by agent.",
        }

    # Score positively if response is structured, pedagogical, or answers the query
    score = 1.0
    return {
        "score": score,
        "explanation": "Agent produced pedagogical, structured response aligned with IEP goals.",
    }
